import { Buffer } from 'node:buffer'
import { createHash } from 'node:crypto'
import type OpenAI from 'openai'
import { CreativeGenerationError } from './creative-generation-types'

import type { CreativeStylePreset } from './creative-generation-types'

export interface ImageGenerationCallInput {
  prompt: string
  model?: string
  size?: '1024x1024' | '1024x1536' | '1536x1024'
  quality?: 'low' | 'medium' | 'high' | 'auto'
  outputFormat?: 'png' | 'jpeg' | 'webp'
  timeoutMs?: number
  stylePreset?: CreativeStylePreset
}

export function applyCreativeStylePreset(prompt: string, preset?: CreativeStylePreset): string {
  if (!preset) return prompt

  if (preset === 'flare') {
    return `${prompt}\n\n[Style Preset: Flare - Atmospheric & Mood Focus]\n- Explicit negative constraint: No humans, no faces, no people.\n- Visual focus: Warm cinematic ambient lighting, aesthetic store interior, logo and branding mood, elegant textures, clean commercial still-life atmosphere.`
  }

  if (preset === 'sunburst') {
    return `${prompt}\n\n[Style Preset: Sunburst - Authentic Human Lifestyle]\n- Explicit positive subject: Authentic Korean person (store owner, professional staff, or happy customer).\n- Visual focus: Hyper-realistic natural skin texture, warm sunburst/golden sunlight, genuine welcoming smile, shallow depth of field, high-end editorial commercial portrait.`
  }

  return prompt
}

export interface ImageGenerationCallOutput {
  bytes: Uint8Array
  mimeType: string
  sha256Digest: string
  providerRequestId: string | null
  model: string
  promptTokensEstimate: number
  imageTokensEstimate: number
  stylePreset?: CreativeStylePreset
}

import { validateImageBinary, ImageBinaryValidationError } from './image-binary-validator'

export function verifyImageBinaryMagic(bytes: Uint8Array): 'image/png' | 'image/jpeg' | 'image/webp' {
  try {
    const validated = validateImageBinary(bytes)
    return validated.mimeType
  } catch (err: any) {
    if (err instanceof ImageBinaryValidationError) {
      if (err.code === 'TRUNCATED_IMAGE_HEADER' || err.code === 'EMPTY_IMAGE_BYTES') {
        throw new CreativeGenerationError('Generated bytes too short for valid image header', 'INVALID_IMAGE_BYTES')
      }
      throw new CreativeGenerationError('Generated binary does not match valid image signature', 'INVALID_IMAGE_HEADER')
    }
    throw err
  }
}

export interface OpenAIImageClient {
  generateImage(input: ImageGenerationCallInput): Promise<ImageGenerationCallOutput>
}

export class DefaultOpenAIImageClient implements OpenAIImageClient {
  private client: Pick<OpenAI, 'images'> | null = null
  private readonly defaultModel: string

  constructor(client?: Pick<OpenAI, 'images'>, model = 'gpt-image-2.5-sunburst') {
    this.client = client || null
    this.defaultModel = model
  }

  private async getClient(): Promise<Pick<OpenAI, 'images'>> {
    if (this.client) return this.client
    const { default: OpenAIClass } = await import('openai')
    const apiKey = process.env.OPENAI_IMAGE_API_KEY || process.env.OPENAI_API_KEY
    if (!apiKey) {
      throw new CreativeGenerationError(
        'OpenAI Image API key is missing (OPENAI_IMAGE_API_KEY required)',
        'IMAGE_AUTH_REQUIRED'
      )
    }
    this.client = new OpenAIClass({ apiKey, dangerouslyAllowBrowser: true })
    return this.client
  }

  async generateImage(input: ImageGenerationCallInput): Promise<ImageGenerationCallOutput> {
    const client = await this.getClient()
    const model = input.model || this.defaultModel
    const enhancedPrompt = applyCreativeStylePreset(input.prompt, input.stylePreset)
    const maxRetries = 2
    let attempt = 0
    let lastError: unknown = null

    while (attempt <= maxRetries) {
      try {
        const generateParams: any = {
          model,
          prompt: enhancedPrompt,
          size: input.size ?? '1024x1024',
          quality: input.quality ?? 'medium',
          output_format: (input.outputFormat ?? 'png') as any,
        }
        if (model.startsWith('dall-e')) {
          generateParams.response_format = 'b64_json'
        }

        const response: any = await client.images.generate(generateParams)

        let bytes: Uint8Array
        const rawB64 = response.data?.[0]?.b64_json
        const imageUrl = response.data?.[0]?.url

        if (rawB64 && typeof rawB64 === 'string') {
          const buffer = Buffer.from(rawB64, 'base64')
          bytes = new Uint8Array(buffer.buffer, buffer.byteOffset, buffer.byteLength)
        } else if (imageUrl && typeof imageUrl === 'string') {
          const imgRes = await fetch(imageUrl)
          if (!imgRes.ok) {
            throw new CreativeGenerationError(
              `Failed to download image payload from OpenAI url (${imgRes.status})`,
              'IMAGE_DOWNLOAD_FAILED'
            )
          }
          const arrayBuf = await imgRes.arrayBuffer()
          bytes = new Uint8Array(arrayBuf)
        } else {
          throw new CreativeGenerationError(
            'OpenAI response missing b64_json and url image data',
            'MISSING_IMAGE_PAYLOAD'
          )
        }

        const mimeType = verifyImageBinaryMagic(bytes)
        const sha256Digest = createHash('sha256').update(bytes).digest('hex')
        const providerRequestId = response._request_id || response.id || null

        // Approximate token/usage estimates according to OpenAI image specs
        const promptTokensEstimate = Math.ceil(input.prompt.length / 4)
        const imageTokensEstimate = input.size === '1024x1024' ? 1024 : 1536

        return {
          bytes,
          mimeType,
          sha256Digest,
          providerRequestId,
          model,
          promptTokensEstimate,
          imageTokensEstimate,
          stylePreset: input.stylePreset,
        }
      } catch (error: any) {
        lastError = error
        const status = error?.status || error?.statusCode
        const code = error?.code || error?.error?.code

        // Fail immediately on unrecoverable client or policy errors
        if (status === 401 || code === 'invalid_api_key') {
          throw new CreativeGenerationError('OpenAI API key authentication rejected', 'IMAGE_AUTH_REQUIRED')
        }
        if (status === 400 || code === 'content_policy_violation' || code === 'billing_hard_limit_reached') {
          throw new CreativeGenerationError(
            `OpenAI request rejected: ${error?.message || code}`,
            code === 'content_policy_violation' ? 'IMAGE_POLICY_REJECTED' : 'IMAGE_PROMPT_INVALID'
          )
        }

        // Retryable: 429 or 5xx
        const isRetryable = status === 429 || (status >= 500 && status < 600)
        if (isRetryable && attempt < maxRetries) {
          attempt++
          const baseDelay = 1000 * Math.pow(2, attempt)
          const jitter = Math.floor(Math.random() * 500)
          await new Promise((resolve) => setTimeout(resolve, baseDelay + jitter))
          continue
        }

        break
      }
    }

    const finalStatus = (lastError as any)?.status
    const finalCode = (lastError as any)?.code
    if (finalStatus === 429) {
      throw new CreativeGenerationError('OpenAI Rate limit exceeded after retries', 'IMAGE_RATE_LIMITED')
    }

    throw new CreativeGenerationError(
      `OpenAI image generation failed: ${(lastError as any)?.message || 'Provider Unavailable'}`,
      finalCode || 'IMAGE_PROVIDER_UNAVAILABLE'
    )
  }
}
