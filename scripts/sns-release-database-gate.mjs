import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { spawnSync } from 'node:child_process'
import { baselineChecks, readyChecks, connectionEnvironment } from './mission-database-gate.mjs'
import { resolveLocalPublicEnv } from './local-public-env.mjs'

const migration = name => readFileSync(new URL(`../supabase/migrations/${name}.sql`, import.meta.url), 'utf8')
const hardening = migration('20261027110000_ani1877_mission_contract_hardening')
const atomic = migration('20261027210000_first_post_atomic_publish_claim')
const credential = migration('20261027215000_meta_credential_save_contract')
const literal = value => `'${value.replaceAll("'", "''")}'`
const assertion = (condition, code) => `BEGIN IF NOT COALESCE((${condition}), false) THEN RAISE EXCEPTION '${code}'; END IF; END;`

function atomicRpcChecks() {
  const definitions = [...`${atomic}\n${credential}`.matchAll(/create (?:or replace )?function (public|private)\.(\w+)\(([\s\S]*?)\)\s*returns (jsonb|boolean|uuid)\s+language (plpgsql|sql)([\s\S]*?)as \$\$([\s\S]*?)\$\$;/gi)]
  if (definitions.length !== 4) throw new Error('SNS_RPC_PARSE_FAILED')
  return definitions.map(([, schema, name, args, result, language, options, body]) => {
    const parameters = args.trim().split(',').map(arg => arg.trim().split(/\s+/))
    const types = parameters.map(p => p[1]).join(',')
    const names = parameters.map(p => literal(p[0])).join(',')
    const server = schema === 'public'
    return assertion(`EXISTS (SELECT 1 FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_language l ON l.oid=p.prolang
      WHERE p.oid=to_regprocedure('${schema}.${name}(${types})')
        AND p.prorettype='${result}'::regtype AND l.lanname='${language}'
        AND p.proargnames=ARRAY[${names}]::text[]
        AND p.pronargdefaults=${parameters.filter(p => p.some(t => t.toLowerCase() === 'default')).length}
        AND p.prosecdef=${server} AND NOT p.proretset
        AND p.provolatile='${/immutable/i.test(options) ? 'i' : 'v'}'
        AND p.proconfig=ARRAY['search_path=""'] AND p.prosrc=${literal(body)}
        AND has_function_privilege('service_role',p.oid,'EXECUTE')=${server}
        AND NOT has_function_privilege('anon',p.oid,'EXECUTE')
        AND NOT has_function_privilege('authenticated',p.oid,'EXECUTE')
        AND NOT EXISTS (SELECT 1 FROM aclexplode(COALESCE(p.proacl,acldefault('f',p.proowner))) a WHERE a.grantee=0 AND a.privilege_type='EXECUTE')
        AND (SELECT count(*) FROM pg_proc other WHERE other.pronamespace=p.pronamespace AND other.proname=p.proname)=1)`, 'SNS_RPC_CONTRACT_OR_PRIVILEGE_DRIFT')
  }).join('\n')
}

// Historical hosted versions were assigned at application time. Do not rewrite that ledger,
// infer name aliases, or replay the repository glob: validate the actual transitive contract.
const rawChecks = [
  baselineChecks(),
  readyChecks([{ version: '20261027110000', sql: hardening }], { requireHistory: false }),
].join('\n').replaceAll('DO $gate$ ', '').replaceAll(' END $gate$;', ' END;') + '\n' + [
  atomicRpcChecks(),
  assertion(`EXISTS (SELECT 1 FROM pg_class WHERE oid=to_regclass('public.first_post_publish_consumptions') AND relrowsecurity)`, 'PUBLISH_CONSUMPTION_RLS_REQUIRED'),
  assertion(`NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid=to_regclass('public.first_post_publish_consumptions') AND contype='u')`, 'PUBLISH_CONTENT_RETRY_CONSTRAINT'),
  assertion(`EXISTS (SELECT 1 FROM pg_index WHERE indexrelid=to_regclass('public.first_post_consumptions_content_idx') AND indisvalid AND indisready AND NOT indisunique)`, 'PUBLISH_CONTENT_INDEX_REQUIRED'),
  assertion(`to_regprocedure('private.first_post_publish_key(jsonb,text)') IS NOT NULL AND to_regprocedure('public.save_meta_channel_connection(uuid,uuid,text,text,text,text,text,text[],timestamptz,timestamptz)') IS NOT NULL`, 'PUBLISH_BASELINE_RPC_REQUIRED'),
].join('\n')

// Fingerprint function source rather than embedding executable-looking source in the probe.
const checks = rawChecks.replace(/p\.prosrc\s*=\s*'((?:[^']|'')*)'/g, (_, source) =>
  `md5(p.prosrc) = '${createHash('md5').update(source.replaceAll("''", "'")).digest('hex')}'`)
export const releaseContract = createHash('sha256').update(checks).digest('hex')
export function buildReadinessMigration() {
  return `-- Generated by scripts/sns-release-database-gate.mjs; no tenant data is returned.\n-- Public callers receive only readiness for this pinned schema/RPC/ACL contract.\nCREATE OR REPLACE FUNCTION public.sns_release_readiness() RETURNS jsonb\nLANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $readiness$\nBEGIN\n${checks}\nRETURN jsonb_build_object('ready',true,'contract','${releaseContract}');\nEXCEPTION WHEN OTHERS THEN\nRETURN jsonb_build_object('ready',false);\nEND;\n$readiness$;\nREVOKE ALL ON FUNCTION public.sns_release_readiness() FROM PUBLIC,anon,authenticated,service_role;\nGRANT EXECUTE ON FUNCTION public.sns_release_readiness() TO anon,authenticated,service_role;\n`
}

const releaseNames = Object.freeze([
  '20261027200000_mission_release_contract',
  '20261027210000_first_post_atomic_publish_claim',
  '20261027215000_meta_credential_save_contract',
  '20261027220000_sns_release_readiness',
])
export function loadReleaseMigrations() {
  return releaseNames.map(name => ({ version: name.slice(0, 14), name: name.slice(15), sql: migration(name) }))
}
export function releasePlanDigest() {
  return createHash('sha256').update(JSON.stringify(loadReleaseMigrations())).digest('hex')
}
export function validateReleaseApproval(env) {
  if (env.GITHUB_ACTIONS !== 'true' || env.GITHUB_REF !== 'refs/heads/main'
      || !/^[a-f0-9]{40}$/.test(env.GITHUB_SHA || '') || env.SNS_APPROVED_SHA !== env.GITHUB_SHA
      || env.SNS_APPROVED_PLAN !== releasePlanDigest() || env.SNS_RELEASE_CONFIRMATION !== 'apply-sns-release') {
    throw new Error('SNS_RELEASE_APPROVAL_REQUIRED')
  }
}
export function buildReleaseApplySql() {
  let sql = `BEGIN;
SET LOCAL statement_timeout='60s';
SET LOCAL lock_timeout='5s';
SELECT pg_advisory_xact_lock(17761877);
LOCK TABLE supabase_migrations.schema_migrations IN EXCLUSIVE MODE;
${baselineChecks()}
`
  // Only append these exact revisions. Historical ledger names/versions are never inferred or repaired.
  for (const row of loadReleaseMigrations()) {
    sql += `DO $history$ ${assertion(`NOT EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations WHERE version=${literal(row.version)} AND (name IS DISTINCT FROM ${literal(row.name)} OR statements IS DISTINCT FROM ARRAY[${literal(row.sql)}]::text[]))`, 'SNS_RELEASE_HISTORY_DRIFT')} $history$;
SELECT NOT EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations WHERE version=${literal(row.version)}) AS pending \\gset
\\if :pending
${row.sql}
INSERT INTO supabase_migrations.schema_migrations(version,name,statements) VALUES (${literal(row.version)},${literal(row.name)},ARRAY[${literal(row.sql)}]);
\\endif
`
  }
  sql += `DO $ready$ ${assertion(`public.sns_release_readiness() = jsonb_build_object('ready',true,'contract',${literal(releaseContract)})`, 'SNS_RELEASE_NOT_READY')} $ready$;
NOTIFY pgrst, 'reload schema';
COMMIT;
`
  return sql
}
export function applyRelease(env = process.env) {
  validateReleaseApproval(env)
  const result = spawnSync('psql', ['-X', '-q', '-A', '-t', '-v', 'ON_ERROR_STOP=1', '-f', '-'], {
    env: connectionEnvironment(env), input: buildReleaseApplySql(), encoding: 'utf8', timeout: 180_000,
    maxBuffer: 2 * 1024 * 1024,
  })
  // SQL errors can contain credential rows or user payloads: never forward subprocess output.
  if (result.error || result.status !== 0) throw new Error('SNS_RELEASE_APPLY_FAILED')
  console.log(`SNS database apply: PASS; plan=${releasePlanDigest()}`)
}

export async function verifyReadiness(url, key, fetcher = fetch) {
  try {
    const response = await fetcher(`${url}/rest/v1/rpc/sns_release_readiness`, {
      method: 'POST', headers: { apikey: key, 'content-type': 'application/json' },
      body: '{}', signal: AbortSignal.timeout(15_000), redirect: 'error',
    })
    if (!response.ok) throw new Error()
    const result = await response.json()
    if (result?.ready !== true || result.contract !== releaseContract) throw new Error()
  } catch {
    // Never expose response bodies, connection settings or customer data in deployment logs.
    throw new Error('SNS_DATABASE_NOT_READY')
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    if (process.argv[2] === 'plan') console.log(`SNS release plan=${releasePlanDigest()}; revisions=${releaseNames.join(',')}`)
    else if (process.argv[2] === 'apply') applyRelease()
    else if (process.argv[2] === 'sql') process.stdout.write(buildReadinessMigration())
    else if (process.argv[2] === 'ready') {
      const config = readFileSync(new URL('../wrangler.jsonc', import.meta.url), 'utf8')
      const env = resolveLocalPublicEnv(process.env, config, { purpose: 'allow-production-read' })
      await verifyReadiness(env.NEXT_PUBLIC_SUPABASE_URL, env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY)
      console.log(`SNS database readiness: PASS; contract=${releaseContract}`)
    } else throw new Error('SNS_GATE_INVALID_MODE')
  } catch {
    console.error('SNS_DATABASE_NOT_READY')
    process.exitCode = 1
  }
}
