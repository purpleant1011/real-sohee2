begin;
create extension if not exists pgtap with schema extensions;
select plan(14);
select has_table('public', 'performance_learning_candidates', 'learning candidates exist');
select has_column('public', 'automation_rules', 'timezone', 'rules retain timezone');
select has_column('public', 'automation_rules', 'next_run_at', 'rules retain next run');
select has_column('public', 'automation_runs', 'scheduled_for', 'runs bind their scheduled time');
select has_column('public', 'automation_runs', 'safe_error_code', 'runs retain only safe errors');
select has_function('public', 'claim_due_v08_automation', array['timestamptz', 'uuid'], 'due claim RPC exists');
select has_function('public', 'complete_v08_automation_run', array['uuid', 'text', 'uuid', 'text'], 'completion RPC exists');
select has_function('public', 'create_performance_learning_candidate', array['uuid', 'uuid', 'jsonb', 'jsonb', 'jsonb', 'jsonb'], 'candidate RPC exists');
select has_function('public', 'review_performance_learning_candidate', array['uuid', 'uuid', 'text', 'text', 'integer'], 'review RPC exists');
select ok((select relrowsecurity from pg_class where oid = 'public.performance_learning_candidates'::regclass), 'learning candidate RLS is enabled');
select ok(not has_function_privilege('authenticated', 'public.claim_due_v08_automation(timestamptz,uuid)', 'EXECUTE'), 'clients cannot claim due rules');
select ok(has_function_privilege('service_role', 'public.claim_due_v08_automation(timestamptz,uuid)', 'EXECUTE'), 'service role may claim due rules');
select ok(not has_function_privilege('authenticated', 'public.complete_v08_automation_run(uuid,text,uuid,text)', 'EXECUTE'), 'clients cannot complete runs directly');
select is((select count(*)::integer from public.performance_learning_candidates where status = 'active'), 0, 'learning candidates never become active before review');
select * from finish();
rollback;
